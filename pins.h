#include <Arduino.h>

// ---------------------------------------------------------------------------
//  1. LED 输出（两个方向各 红/黄/绿，每颗串 220Ω 电阻）
// ---------------------------------------------------------------------------
#define PIN_NS_R   4      // 南北向 红
#define PIN_NS_Y   5      // 南北向 黄
#define PIN_NS_G   6      // 南北向 绿
#define PIN_EW_R   7      // 东西向 红
#define PIN_EW_Y   8      // 东西向 黄
#define PIN_EW_G   9      // 东西向 绿

// ---------------------------------------------------------------------------
//  2. 按键输入（INPUT_PULLUP：不按读到 HIGH，按下读到 LOW，别搞反）
//     ⚠ Uno 上能接外部中断的只有 D2 和 D3，不要挪到别的脚。
// ---------------------------------------------------------------------------
#define PIN_PED    2      // 行人过街请求（INT0）
#define PIN_EMG    3      // 紧急车辆请求（INT1）

// ---------------------------------------------------------------------------
//  3. 超声波 HC-SR04
// ---------------------------------------------------------------------------
#define PIN_TRIG   10
#define PIN_ECHO   11

// ---------------------------------------------------------------------------
//  4. 蜂鸣器（有源，高电平响）
// ---------------------------------------------------------------------------
#define PIN_BUZZ   12

// ---------------------------------------------------------------------------
//  5. LCD1602 + I2C 转接板（I2C 固定走 A4=SDA / A5=SCL，不需要宏）
// ---------------------------------------------------------------------------
#define LCD_I2C_ADDR   0x27     // 背光亮但没字 → 先看串口里的 I2C 扫描结果，可能是 0x3F
#define LCD_COLS       16
#define LCD_ROWS       2

// ---------------------------------------------------------------------------
//  6. 编译开关
// ---------------------------------------------------------------------------
//  已启用：依赖库 "LiquidCrystal I2C"（Frank de Brabander，1.1.2）。
//  改回 0 可回到"零第三方依赖"状态（只输出串口，不驱动屏幕）。
#define USE_LCD1602    1

// ---------------------------------------------------------------------------
//  7. 可调参数（改完记得重新跑一遍仿真）
// ---------------------------------------------------------------------------
#define SERIAL_BAUD            9600
#define DEBOUNCE_MS            30          // 按键消抖窗口（毫秒）
#define ULTRASONIC_TIMEOUT_US  25000UL     // pulseIn 超时微秒数。⚠ 不传它就会卡 1 秒
#define SMOOTH_SAMPLES         5           // 测距滑动窗口样本数
#define ULTRASONIC_INTERVAL_MS 60          // 两次测距最小间隔（HC-SR04 规格要求 ≥60ms）

// ---------------------------------------------------------------------------
//  8. 相位（状态机的状态集合）
// ---------------------------------------------------------------------------
//  正常循环：NS_GREEN → NS_YELLOW → ALL_RED → EW_GREEN → EW_YELLOW → ALL_RED → ……
//  ALL_RED 是"全红清空期"，也是行人过街相位的插入点。
enum Phase {
  PHASE_NS_GREEN = 0,
  PHASE_NS_YELLOW,
  PHASE_EW_GREEN,
  PHASE_EW_YELLOW,
  PHASE_ALL_RED
};

// ---------------------------------------------------------------------------
//  9. 各相位的默认时长与上下限（毫秒）
// ---------------------------------------------------------------------------
#define T_YELLOW        3000UL     // 黄灯
#define T_ALL_RED       1500UL     // 全红清空期
#define GREEN_MIN       4000UL     // 绿灯下限（没有它会出现"饥饿"）
#define GREEN_BASE      8000UL     // 绿灯基准值（测距失效时的退路）
#define GREEN_MAX      20000UL     // 绿灯上限（没有它另一方向会等到崩溃）
#define T_PED_CROSS     5000UL     // 行人过街占用全红的时长
#define T_EMG_HOLD      5000UL     // 紧急车辆优先占用全红的时长
