#pragma once
#include <Arduino.h>
#include "pins.h"

// ============================================================================
//  phases.h  ·  任务一：四相位状态机与灯输出          【甲 负责】
// ----------------------------------------------------------------------------
//  ⚠ 本文件里的所有函数签名都是"冻结接口"：乙的显示模块和行人模块会调用它们。
//    改签名之前必须先通知乙。
//
//  对应指导文档：§1.3 任务一、§1.4 任务二（用到 phasesGoto）
// ============================================================================

// --- 生命周期 -------------------------------------------------------------
// setup() 里调用一次：把六个灯设为输出、点亮初始相位。
void phasesInit();

// loop() 里每轮调用一次。★ 任务一要你实现的就是这个函数 ★
// 必须是非阻塞写法：到点就换相位，没到点就立刻返回。
void phasesUpdate(unsigned long now);

// --- 输出 -----------------------------------------------------------------
// 把当前相位对应的灯点亮，其余全灭（内部用查表法，已写好）。
void phasesApplyLights();

// 开机自检：六个灯依次点亮 0.5 秒。
// 这是环境的基础设施（不是任务），用来判断"接线和下载链路对不对"。
void phasesSelfTest();

// 相位名字，串口与 LCD 显示用。
const char* phasesName(Phase p);

// --- 状态查询 -------------------------------------------------------------
Phase         phasesCurrent();                        // 当前相位
unsigned long phasesStartMillis();                    // 本相位开始的时刻
unsigned long phasesDuration();                       // 本相位的总时长
unsigned long phasesRemainMs(unsigned long now);      // 还剩多少毫秒（倒计时显示用）

// --- 状态控制 -------------------------------------------------------------
// 改写本相位的时长。动态配时算法（green_time）用它写入算好的绿灯时长。
void phasesSetDuration(unsigned long ms);

// 强制跳到某个相位并重置计时。
// 行人过街 / 紧急车辆优先用它来"插队"。
void phasesGoto(Phase p, unsigned long durMs, unsigned long now);
